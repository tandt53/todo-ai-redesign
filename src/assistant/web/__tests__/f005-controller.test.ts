describe('AC-38 — a passed reminder is surfaced on open', () => {
  const passed = (over: Partial<TaskWire> = {}): TaskWire =>
    task({
      id: 'r1',
      title: 'Ring the dentist',
      reminder_at: '2026-08-15T09:00:00.000Z',
      reminder_shown_at: null,
      ...over,
    })

  it('one installer, and every reminder whose instant has passed and is unacknowledged is surfaced', () => {
    const h = scripted()
    h.controller.state = {
      ...h.controller.state,
      tasks: [
        passed({ id: 'old', reminder_at: '2026-08-10T09:00:00.000Z' }),
        passed({ id: 'newer', reminder_at: '2026-08-15T09:00:00.000Z' }),
        // future — not passed
        passed({ id: 'future', reminder_at: '2026-09-01T09:00:00.000Z' }),
        // acknowledged — a STORED fact, so it does not reappear on this launch, on
        // the next device, or after a reload
        passed({ id: 'acked', reminder_shown_at: T0 }),
        // done and deleted are not surfaced
        passed({ id: 'done', status: 'done' }),
        passed({ id: 'gone', deleted_at: T0 }),
      ],
    }

    h.controller.openingSync()

    // **N passed reminders are ONE surfacing, ordered oldest first** (tester W7,
    // product P3): a user returning after two weeks meets the whole set at once.
    expect(h.controller.state.reminders.map((r) => r.taskId)).toEqual(['old', 'newer'])
    expect(h.controller.state.announce?.text).toBe('2 reminders have passed.')
  })

  it('RENDERING is not resolution — reopening still surfaces an unacknowledged reminder', () => {
    // product P1, design D16: *"a user who opens the app, is interrupted and closes
    // it has spent their only delivery — on every device, permanently — while the
    // task is still undone."* The negative case is what makes this assertable, and
    // it is constructible because *"do not acknowledge"* is now a precondition
    // rather than an open gesture set.
    const h = scripted()
    h.controller.state = { ...h.controller.state, tasks: [passed()] }
    h.controller.openingSync()
    expect(h.controller.state.reminders).toHaveLength(1)
    // open, DO NOT acknowledge, reopen
    h.controller.openingSync()
    expect(h.controller.state.reminders, 'still there').toHaveLength(1)
    expect(h.server.calls.filter((c) => c.path.includes('reminder-ack'))).toHaveLength(0)
  })

  it('acknowledging is per-reminder and sends the INSTANT, so a moved reminder cannot be retired', async () => {
    const h = scripted()
    h.controller.state = {
      ...h.controller.state,
      tasks: [passed({ id: 'a' }), passed({ id: 'b', reminder_at: '2026-08-16T09:00:00.000Z' })],
    }
    h.controller.openingSync()
    h.server.always('POST /tasks/:id/reminder-ack', 200, {
      task: passed({ id: 'a', reminder_shown_at: T0 }),
      acknowledged: true,
    })

    await h.controller.acknowledgeReminder('a')

    // **Only what the user acknowledges is marked**: ten surfaced together of which
    // three were acted on do not silently retire the other seven. **No bulk
    // dismissal.**
    expect(h.controller.state.reminders.map((r) => r.taskId)).toEqual(['b'])
    const ack = h.server.calls.find((c) => c.path.includes('reminder-ack'))
    expect(ack?.body).toEqual({ reminder_at: '2026-08-15T09:00:00.000Z' })
  })

  it('offline, an acknowledgement is NOT recorded and the reminder re-surfaces at the next open', async () => {
    // The owner's correction of 2026-08-19: revision 3 said the acknowledgement *"is
    // recorded when connectivity returns"*, and that is the one mechanism the
    // owner's own answer forbids by name — **queue-and-replay for one field is
    // queue-and-replay**, arriving through a side door.
    const h = harness({ online: false })
    h.controller.state = { ...h.controller.state, tasks: [passed()], offline: true }
    h.controller.openingSync()

    await h.controller.acknowledgeReminder('r1')

    expect(h.server.calls.filter((c) => c.path.includes('reminder-ack'))).toHaveLength(0)
    expect(h.controller.state.announce?.text).toContain('come back next time')
    // Nothing durable changed, so the next open surfaces it again.
    h.controller.openingSync()
    expect(h.controller.state.reminders).toHaveLength(1)
  })

  it('a 409 REMINDER_MOVED puts it back rather than retiring one the server did not mark', async () => {
    const h = scripted()
    h.controller.state = { ...h.controller.state, tasks: [passed()] }
    h.controller.openingSync()
    h.server.always('POST /tasks/:id/reminder-ack', 409, {
      error: { code: 'REMINDER_MOVED', message: 'moved' },
    })

    await h.controller.acknowledgeReminder('r1')

    expect(h.controller.state.reminders, 'a reminder wrongly retired is not recoverable').toHaveLength(1)
  })
})

