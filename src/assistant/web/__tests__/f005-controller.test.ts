describe('AC-2 / AC-26 — the receiver clause', () => {
  it('applies the addressed row AND every member of `changed` — the successor is drawn with no refresh', async () => {
    // AC-26's own case, and the reason the receiver half exists: *"a successor
    // generated by a hand tick appears NOWHERE until some unrelated event
    // refreshes, at which point a row the user never created materialises with no
    // gesture attached."*
    const occurrence = todayTask({ id: 'occ-1', title: 'Water the plants', series_live: true })
    const successor = task({
      id: 'occ-2',
      title: 'Water the plants',
      due_at: '2026-08-26T00:00:00.000Z',
      series_id: 'series-1',
      series_live: true,
    })
    const h = scripted()
    h.controller.state = { ...h.controller.state, tasks: [occurrence] }
    h.server.always('PATCH /tasks/:id', 200, {
      task: { ...occurrence, status: 'done' },
      changed: [successor],
    })

    await h.controller.toggleTask('occ-1')

    expect(find(h, 'occ-1')?.status).toBe('done')
    expect(find(h, 'occ-2'), 'the successor the write returned').toBeDefined()
    // …and it arrived from the RESPONSE, not from a blind re-read. The rows were
    // already in hand, which is why api-contracts rejects the `GET` alternative.
    expect(h.server.calls.filter((c) => c.method === 'GET' && c.path === '/tasks')).toHaveLength(0)
    // AC-39's mark has something to be about on this client now — which is the
    // whole of what "vacuously true" meant before.
    expect(seriesLive(find(h, 'occ-2') as TaskWire)).toBe(true)
  })

  it('drops every id in `removed` — AC-28’s successor removal is a HARD removal', async () => {
    // *"Removes the successor" is a hard removal, not a soft delete* (architect L1):
    // a soft-removed successor is a row AC-41 can restore, producing the second open
    // occurrence the whole recurrence section rests on not having.
    const done = todayTask({ id: 'occ-1', status: 'done', series_live: true })
    const successor = task({ id: 'occ-2', series_id: 'series-1', series_live: true })
    const h = scripted()
    h.controller.state = { ...h.controller.state, tasks: [done, successor] }
    h.server.always('PATCH /tasks/:id', 200, {
      task: { ...done, status: 'inbox' },
      changed: [],
      removed: ['occ-2'],
    })

    await h.controller.toggleTask('occ-1')

    expect(find(h, 'occ-1')?.status).toBe('inbox')
    expect(find(h, 'occ-2'), 'the removed successor is gone from client state').toBeUndefined()
  })

  it('applies AC-19’s cascade — steps ticked by their parent arrive in `changed`', async () => {
    const parent = todayTask({ id: 'p1', title: 'Pack' })
    const s1 = task({ id: 's1', title: 'passport', parent_id: 'p1', step_order: 1024 })
    const s2 = task({ id: 's2', title: 'charger', parent_id: 'p1', step_order: 2048 })
    const h = scripted()
    h.controller.state = { ...h.controller.state, tasks: [parent, s1, s2] }
    h.server.always('PATCH /tasks/:id', 200, {
      task: { ...parent, status: 'done' },
      changed: [
        { ...s1, status: 'done', completed_by_parent: true },
        { ...s2, status: 'done', completed_by_parent: true },
      ],
    })

    await h.controller.toggleTask('p1')

    expect(find(h, 's1')?.status).toBe('done')
    expect(find(h, 's2')?.status).toBe('done')
    // AC-35 — and the steps are still in NO collection, on either client, which is
    // *"the cascade neither corrupts the list nor leaves a step visible"*.
    const now = new Date(T0)
    for (const c of ['inbox', 'today', 'upcoming', 'done'] as const) {
      expect(inCollection(find(h, 's1') as TaskWire, c, now), `s1 in ${c}`).toBe(false)
    }
    // …and the parent's own remaining count is a different number about a
    // different set (AC-17), which is now zero rather than absent.
    expect(remainingSteps(h.controller.state.tasks, 'p1')).toBe(0)
  })

  it('tolerates a 2xx with no `task` rather than throwing — a server bug is not a dead surface', async () => {
    const row = todayTask({ id: 't1' })
    const h = scripted()
    h.controller.state = { ...h.controller.state, tasks: [row] }
    h.server.always('PATCH /tasks/:id', 200, {})
    await expect(h.controller.toggleTask('t1')).resolves.toBeUndefined()
    // The optimistic value stands, which is what the code did before the receiver
    // clause existed — so a stub answering `{}` behaves exactly as it used to.
    expect(find(h, 't1')?.status).toBe('done')
  })
})

