// F-005 — the shared controller's half, under node.
//
// Everything asserted here lives in `src/assistant/_shared/`, **which the mobile
// client compiles**, so every case is a case about both clients:
//
//   - **AC-2 / AC-26's receiver clause.** The sender obligation is the server's;
//     without the receiver, AC-39 is *vacuously true on the platform it was created
//     for* — the successor is never drawn on the phone, so no mutation of the repeat
//     mark can turn the mobile case red.
//   - **AC-2's third state, scoped by row PROVENANCE.** The clause four lenses
//     caught, and the one most likely to be got wrong: unscoped, it removes working
//     behaviour, and QA writes from the spec, so the test would have asserted the
//     refusal and the regression would have shipped green.
//   - **AC-47's notice**, whose mechanism must observe *every* write to a field.
//   - **AC-14 / AC-13's replay literal**, which produces no compile error when a
//     field is missed.
//   - **AC-44's one clock**, driven by the one seam.
//   - **AC-38's opening installer**, and **AC-43's single-slot offer**.

