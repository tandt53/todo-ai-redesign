describe('AC-14 / AC-13 — the offline create replay carries the whole field set', () => {
  it('an offline-created STEP replays with its parent and its position — not as a top-level task', async () => {
    // *"Read the wrong way an offline-created step replays with `parent_id` dropped
    // and returns as an ordinary top-level task, in every collection and every
    // count, which is what AC-35 exists to prevent."*
    const h = scripted({ online: false })
    await h.controller.init()
    // The offline create path is F-001 AC-25's; a step made offline is the row that
    // reaches the replay carrying structure, so it is built through the store the
    // replay actually reads.
    const local = task({
      id: 'local-step',
      title: 'passport',
      parent_id: 'parent-1',
      step_order: 2048,
      due_all_day: true,
      note: 'in the drawer',
      reminder_at: '2026-08-20T09:00:00.000Z',
      priority: 'high',
    })
    h.stores.saveLocalTasks([{ ...local, local: true }])
    // The replay ends with a read-back — *"the server is the authority now"* — so
    // the read has to answer the contract's shape rather than the fake's catch-all.
    h.server.always('GET /tasks', 200, { tasks: [] })

    h.controller.setOnline(true)
    await settle()

    const posted = h.server.calls.filter((c) => c.method === 'POST' && c.path === '/tasks')
    expect(posted).toHaveLength(1)
    expect(posted[0]?.body).toMatchObject({
      id: 'local-step',
      parent_id: 'parent-1',
      step_order: 2048,
      due_all_day: true,
      note: 'in the drawer',
      reminder_at: '2026-08-20T09:00:00.000Z',
      priority: 'high',
    })
  })

  it('a task created offline on TODAY replays as all-day — never a bare local midnight', async () => {
    // AC-13's third writer (dev-mobile F5), and ADR-010's answer: the offline create
    // *"computes in the device zone and stores the answer rather than deferring
    // it"*. Without the flag the row renders as **"12:00 AM"**.
    const h = scripted({ online: false })
    await h.controller.init()
    await h.controller.addTask('bought offline', 'today')
    const created = h.controller.state.tasks[0] as TaskWire
    expect(created.due_at).toBe(startOfTodayIso(new Date(T0)))
    expect(created.due_all_day, 'the flag is stored at creation, not deferred').toBe(true)

    h.server.always('GET /tasks', 200, { tasks: [] })
    h.controller.setOnline(true)
    await settle()

    const posted = h.server.calls.filter((c) => c.method === 'POST' && c.path === '/tasks')
    expect(posted[0]?.body).toMatchObject({ due_all_day: true })
  })

  it('and the row renders with NO clock time — the defect AC-13 forbids, on the landing collection', () => {
    const now = new Date(T0)
    const midnight = startOfTodayIso(now)
    // What shipped: a clock time for a time nobody picked.
    expect(formatDue(midnight, now)).toBe('12:00 AM')
    // What AC-13 requires, once the flag travels with the instant.
    expect(formatDue(midnight, now, { allDay: true })).toBe('Today')
  })
})

