describe('AC-47 — the notice, and who supersedes it', () => {
  it('a later write by ANYONE supersedes it: the notice STANDS, reports, and loses its retry', async () => {
    // *"A later successful write supersedes the notice whoever made it — the user's
    // retry or an assistant turn — and a supersede by a turn is announced rather
    // than silent."* Both halves matter: ending it silently discards a typed value
    // without saying so; keeping the retry is a control that overwrites the newer
    // stored value with the stale failed one.
    const row = todayTask({ id: 't1', title: 'Original' })
    const h = scripted()
    h.controller.state = { ...h.controller.state, tasks: [row] }
    h.server.always('PATCH /tasks/:id', 500, { error: { code: 'INTERNAL', message: 'boom' } })
    await h.controller.writeField('t1', { title: 'Typed' })
    expect(retryableFields(noticeFor(h.controller.state.notices, 't1')!)).toHaveLength(1)

    // An assistant turn renames the same field — arriving through the refresh path,
    // which is one of the four writers the mechanism has to observe.
    h.server.always('GET /tasks', 200, { tasks: [{ ...row, title: 'Renamed by the assistant' }] })
    await h.controller.refreshTasks()

    const n = noticeFor(h.controller.state.notices, 't1')
    expect(n, 'the notice STANDS — supersession is not an ender').not.toBeNull()
    expect(n?.fields[0]?.superseded).toBe(true)
    expect(n?.fields[0]?.value, 'and it still carries what the user typed').toBe('Typed')
    expect(n?.fields[0]?.storedNow, 'and says which value the field holds now').toBe(
      'Renamed by the assistant',
    )
    // **No retry.** The resurrection door AC-4 and AC-47 close everywhere else.
    expect(retryableFields(n!)).toHaveLength(0)
    // …and a retry invoked anyway is a no-op rather than a stale write.
    await h.controller.retryNotice('t1', 'title')
    expect(find(h, 't1')?.title).toBe('Renamed by the assistant')
  })

  it('a retry that SUCCEEDS is the one path that removes the field', async () => {
    const row = todayTask({ id: 't1', title: 'Original' })
    const h = scripted()
    h.controller.state = { ...h.controller.state, tasks: [row] }
    h.server.once('PATCH /tasks/:id', 500, { error: { code: 'INTERNAL', message: 'boom' } })
    await h.controller.writeField('t1', { title: 'Typed' })
    expect(noticeFor(h.controller.state.notices, 't1')).not.toBeNull()

    h.server.always('PATCH /tasks/:id', 200, { task: { ...row, title: 'Typed' } })
    await h.controller.retryNotice('t1', 'title')

    expect(noticeFor(h.controller.state.notices, 't1')).toBeNull()
    expect(find(h, 't1')?.title).toBe('Typed')
  })

  it('the task being DELETED ends the notice as a report — value legible, no retry', async () => {
    // AC-4 / AC-47, tester W9, design D20: reachable from an ordinary sequence —
    // fail a write, close the detail, say *"delete that"*.
    const row = todayTask({ id: 't1', title: 'Original' })
    const h = scripted()
    h.controller.state = { ...h.controller.state, tasks: [row] }
    h.server.once('PATCH /tasks/:id', 500, { error: { code: 'INTERNAL', message: 'boom' } })
    await h.controller.writeField('t1', { title: 'Typed' })

    h.server.always('DELETE /tasks/:id', 200, { task: { ...row, deleted_at: T0 } })
    await h.controller.removeTask('t1')

    const n = noticeFor(h.controller.state.notices, 't1')
    expect(n?.ended).toBe('task-deleted')
    expect(n?.fields[0]?.value, 'the value is still legible').toBe('Typed')
    expect(retryableFields(n!), 'and there is no retry').toHaveLength(0)
  })

  it('a rename reaches the notice, because after the row is gone it holds the only copy of the name', async () => {
    const row = todayTask({ id: 't1', title: 'Original' })
    const h = scripted()
    h.controller.state = { ...h.controller.state, tasks: [row] }
    h.server.once('PATCH /tasks/:id', 500, { error: { code: 'INTERNAL', message: 'x' } })
    await h.controller.writeField('t1', { note: 'a note that failed' })
    expect(noticeFor(h.controller.state.notices, 't1')?.taskTitle).toBe('Original')

    h.server.always('GET /tasks', 200, { tasks: [{ ...row, title: 'Renamed' }] })
    await h.controller.refreshTasks()

    expect(noticeFor(h.controller.state.notices, 't1')?.taskTitle).toBe('Renamed')
  })

  it('a single-row response says NOTHING about other tasks, and ends none of their notices', async () => {
    // The trap in `reconcileNotices`: ending a notice on *absence from this response*
    // would end every notice on every single-row write. Only KNOWN deletion ends one.
    const a = todayTask({ id: 'a', title: 'A' })
    const b = todayTask({ id: 'b', title: 'B' })
    const h = scripted()
    h.controller.state = { ...h.controller.state, tasks: [a, b] }
    h.server.once('PATCH /tasks/:id', 500, { error: { code: 'INTERNAL', message: 'x' } })
    await h.controller.writeField('a', { title: 'typed on A' })

    h.server.always('PATCH /tasks/:id', 200, { task: { ...b, title: 'B2' } })
    await h.controller.writeField('b', { title: 'B2' })

    const n = noticeFor(h.controller.state.notices, 'a')
    expect(n?.ended, 'A’s notice is untouched by a write about B').toBeNull()
    expect(retryableFields(n!)).toHaveLength(1)
  })

  it('the user dismissing it is the only user ender', () => {
    const h = scripted()
    h.controller.state = {
      ...h.controller.state,
      notices: [
        {
          taskId: 't1',
          taskTitle: 'X',
          fields: [{ field: 'title', value: 'v', baseline: 'o', reason: 'failed', superseded: false }],
          ended: null,
          at: T0,
        },
      ],
    }
    h.controller.dismissNotice('t1')
    expect(h.controller.state.notices).toEqual([])
  })
})

