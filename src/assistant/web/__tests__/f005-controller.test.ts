const settle = async (): Promise<void> => {
  await Promise.resolve()
  await new Promise((r) => setTimeout(r, 0))
  await Promise.resolve()
}

/**
 * A controller whose session read answers the contract's *no open session* shape.
 *
 * `init()` walks the session route, and the fake's catch-all `200 {}` is not a
 * `SessionReadWire` — so a suite that drives `init()` has to say what the session
 * read returns, or it is asserting against a response the server cannot send.
 */
function scripted(opts: { online?: boolean } = {}) {
  const h = harness(opts)
  h.server.always('GET /assistant/session', 200, { session: null, boundary: null })
  return h
}

const find = (h: ReturnType<typeof harness>, id: string): TaskView | undefined =>
  h.controller.state.tasks.find((t) => t.id === id)

