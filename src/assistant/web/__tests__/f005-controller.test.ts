describe('AC-35 — the one gate that reaches both clients', () => {
  it('a step is in NO collection, open or done — the gate sits before the done gate', () => {
    const now = new Date(T0)
    const openStep = task({ id: 's', parent_id: 'p', step_order: 1024 }) as TaskWire
    const doneStep = task({ id: 's2', parent_id: 'p', step_order: 2048, status: 'done' }) as TaskWire
    expect(isStep(openStep)).toBe(true)
    for (const c of ['inbox', 'today', 'upcoming', 'done'] as const) {
      expect(inCollection(openStep, c, now), `open step in ${c}`).toBe(false)
      // The done case is a real difference and not ordering taste: a done step must
      // be in Done no more than an open one is in Today, or AC-19's cascade puts
      // eight rows the user has never seen into a collection as top-level rows.
      expect(inCollection(doneStep, c, now), `done step in ${c}`).toBe(false)
    }
  })

  it('AC-17’s count is a different number about a different set — never a collection count', () => {
    const tasks = [
      todayTask({ id: 'p', title: 'Pack' }),
      task({ id: 's1', parent_id: 'p', step_order: 1024 }),
      task({ id: 's2', parent_id: 'p', step_order: 2048, status: 'done' }),
      task({ id: 's3', parent_id: 'p', step_order: 3072 }),
    ]
    expect(remainingSteps(tasks, 'p')).toBe(2)
    // A task with no steps shows nothing — the AC's own negative half.
    expect(remainingSteps(tasks, 's1')).toBe(0)
  })
})
