describe('AC-2 / AC-42 — a write that FAILED', () => {
  it('a failed field write reverts the row to what the server holds and keeps the value in a notice', async () => {
    const row = todayTask({ id: 't1', title: 'Original' })
    const h = scripted()
    h.controller.state = { ...h.controller.state, tasks: [row] }
    h.server.always('PATCH /tasks/:id', 500, { error: { code: 'INTERNAL', message: 'boom' } })

    await h.controller.editTask('t1', 'Typed but not saved')

    expect(find(h, 't1')?.title, 'the row shows what the store holds').toBe('Original')
    const n = noticeFor(h.controller.state.notices, 't1')
    expect(n?.fields[0]).toMatchObject({ field: 'title', value: 'Typed but not saved', reason: 'failed' })
    expect(n?.ended).toBeNull()
  })

  it('a FAILED delete brings the row back, states it, and is NOT an undo case', async () => {
    // dev-backend F7: `removeTask` never inspected its result, so on a failed
    // `DELETE` the row was already gone locally with nothing on the server to
    // reverse — an undo would call AC-41's restore on a live row and tell the user
    // something was restored that was never deleted. **The offer follows the
    // write's RESULT.**
    const row = todayTask({ id: 't1', title: 'Still here' })
    const h = scripted()
    h.controller.state = { ...h.controller.state, tasks: [row] }
    h.server.always('DELETE /tasks/:id', 500, { error: { code: 'INTERNAL', message: 'boom' } })

    await h.controller.removeTask('t1')

    expect(find(h, 't1'), 'the row comes back').toBeDefined()
    expect(h.controller.state.undoOffer).toBeNull()
    expect(h.controller.state.announce?.text).toContain("wasn't deleted")
  })

  it('a write that fails BECAUSE THE TASK IS GONE produces no notice at all (AC-4)', async () => {
    // *"There is nothing to retry and nothing to write into: a notice offering retry
    // on a deleted task is either dead or a resurrection, and AC-4 forbids both.
    // AC-4's terminal state remains the whole of that case."*
    const row = todayTask({ id: 't1', title: 'Original' })
    const h = scripted()
    h.controller.state = { ...h.controller.state, tasks: [row] }
    h.server.always('PATCH /tasks/:id', 404, { error: { code: 'NOT_FOUND', message: 'gone' } })

    await h.controller.editTask('t1', 'Typed')

    expect(noticeFor(h.controller.state.notices, 't1')).toBeNull()
    expect(h.controller.state.announce?.text).toContain('is gone')
  })

  it('concurrent failures report ONCE, naming the fields — not one announcement per field', async () => {
    // AC-2, design D4: *"One polite announcement per failure technically satisfies
    // 4.1.3 while making the surface unusable for exactly the users AC-16 and AC-33
    // exist for."*
    const row = todayTask({ id: 't1', title: 'Original', note: null })
    const h = scripted()
    h.controller.state = { ...h.controller.state, tasks: [row] }
    h.server.always('PATCH /tasks/:id', 500, { error: { code: 'INTERNAL', message: 'boom' } })

    await h.controller.writeField('t1', { title: 'A' })
    await h.controller.writeField('t1', { note: 'B' })

    // ONE notice for the task, carrying both fields (AC-47's aggregation).
    expect(h.controller.state.notices).toHaveLength(1)
    const n = noticeFor(h.controller.state.notices, 't1')
    expect(n?.fields.map((f) => f.field).sort()).toEqual(['note', 'title'])
    // …and ONE sentence naming both.
    const said = h.controller.state.announce?.text ?? ''
    expect(said).toContain('name')
    expect(said).toContain('note')
  })
})

