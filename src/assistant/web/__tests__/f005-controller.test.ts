describe('AC-2 — the offline state is scoped by row PROVENANCE', () => {
  it('a SERVER-OWNED row is refused: nothing sent, the value not applied, the reason stated', async () => {
    const row = todayTask({ id: 'srv-1', title: 'Call the bank' })
    const h = harness({ online: false })
    h.controller.state = { ...h.controller.state, tasks: [row], offline: true }

    await h.controller.editTask('srv-1', 'Call the bank back')

    // **Never sent.** Not queued, not stored, not replayed — *"there is no NEW
    // queue, no NEW durable store and no replay of edits"*.
    expect(h.server.calls.filter((c) => c.method === 'PATCH')).toHaveLength(0)
    expect(h.stores.localTasks()).toEqual([])
    // The row shows what the server holds. AC-2's mobile-tier outcome: *"the row
    // shows the value the server holds and the failure is stated — never a row that
    // vanishes and returns at the next refresh"*.
    expect(find(h, 'srv-1')?.title).toBe('Call the bank')
    // The value is not lost either: it is in the notice, with a user-invoked retry.
    const n = noticeFor(h.controller.state.notices, 'srv-1')
    expect(n?.fields.map((f) => [f.field, f.value, f.reason])).toEqual([
      ['title', 'Call the bank back', 'offline-refused'],
    ])
    expect(retryableFields(n!).map((f) => f.field)).toEqual(['title'])
    // …and the reason given is an OFFLINE refusal, announced under 4.1.3.
    expect(h.controller.state.announce?.text).toContain("offline")
  })

  it('a LOCALLY-CREATED row is kept and replayed, exactly as it is today', async () => {
    // **The clause four lenses caught.** The shipped guard has three disjuncts and
    // the unscoped rule inverted the behaviour on the first: create a task offline
    // under F-001 AC-25, then be unable to fix a typo in it. `persistLocal()`
    // genuinely saves the edit and `pushLocalTasks` genuinely replays it — that
    // store and that replay ship today, and this AC neither builds nor widens them.
    const h = scripted({ online: false })
    await h.controller.init()
    await h.controller.addTask('typo')
    const id = h.controller.state.tasks[0]?.id as string
    expect(find(h, id)?.local).toBe(true)

    await h.controller.editTask(id, 'fixed')

    expect(find(h, id)?.title, 'the edit is APPLIED, not refused').toBe('fixed')
    expect(h.stores.localTasks().map((t) => t.title), 'and it is durably saved').toEqual(['fixed'])
    // No notice: nothing failed and nothing was refused.
    expect(noticeFor(h.controller.state.notices, id)).toBeNull()
  })

  it('the first disjunct fires WHILE ONLINE, and the refusal never claims otherwise', async () => {
    // *"An unsynced local row whose replay failed stays `local: true` with
    // connectivity restored. Scoping the refusal by provenance removes that case
    // entirely: the offline refusal is stated only when the app is actually offline,
    // so the reason given is never one the user can disprove by looking at their
    // connection."*
    const h = scripted({ online: false })
    await h.controller.init()
    await h.controller.addTask('made offline')
    const id = h.controller.state.tasks[0]?.id as string
    // Back online, replay not done — the row is still `local: true`.
    h.controller.state = { ...h.controller.state, offline: false }
    expect(find(h, id)?.local).toBe(true)

    await h.controller.editTask(id, 'renamed while online')

    expect(find(h, id)?.title).toBe('renamed while online')
    expect(
      h.controller.state.announce?.text ?? '',
      'no "you are offline" for a row edited while online',
    ).not.toContain('offline')
  })

  it('a server-owned DELETE offline is refused, the row stays, and NO undo offer is made', async () => {
    // AC-43's mobile bullet: *"Offline it cannot run at all: `removeTask` never
    // reaches the server and AC-41's restore is a server call, so the delete is
    // AC-2's offline refusal and no offer is made."*
    const row = todayTask({ id: 'srv-1', title: 'Pay the bill' })
    const h = harness({ online: false })
    h.controller.state = { ...h.controller.state, tasks: [row], offline: true }

    await h.controller.removeTask('srv-1')

    expect(h.server.calls.filter((c) => c.method === 'DELETE')).toHaveLength(0)
    expect(find(h, 'srv-1'), 'the row stays').toBeDefined()
    expect(h.controller.state.undoOffer, 'an offer would point at a row nothing deleted').toBeNull()
  })
})

